import SwiftUI

// ============================================================ 内容列封顶
//
// 看盘整套界面是照 iPhone 宽度画的，iPad 只要求「不破」（2026-09-18 用户定的口径）：
// 每一页在 iPad 全部宽度下不错位、不拉伸、可用，但**不**做一套宽屏分栏布局。
//
// 满屏铺开的那几页（搜索页、品种整页、复盘本）都是「左边一个名字、右边一个数字」
// 的行。这种行在 iPhone 上两端相距 350pt 左右，一眼扫得过来；到了 13" iPad 横屏
// 就是 1300pt——BTC 在最左边，它的价格在一米开外的最右边，中间一片空白，人得来回
// 找。这不是好看不好看的问题，是读不通。
//
// 所以给这类整页内容一个和大号 iPhone 相当的宽度上限，居中放；iPhone 上上限比屏还宽，
// 等于没有这一层。页面底色仍然由调用方铺在封顶**外面**，两侧不会露出白边。
//
// 只用于「一列到底」的页面。K 线图区不用——图就是要占满；弹层（`.sheet`）也不用——
// iPad 上系统本来就把它收成居中的卡片。
extension View {
  /// 把内容列封在 `max` 宽以内并居中（默认 560pt，比最宽的 iPhone 再富余一点）。
  func readableColumn(_ max: CGFloat = 560) -> some View {
    frame(maxWidth: max).frame(maxWidth: .infinity)
  }
}
