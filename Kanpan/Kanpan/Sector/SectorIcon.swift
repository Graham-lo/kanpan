/// 板块记号：一个板块一枚，共 40 枚（冻结原型的 37 枚 + 后补的 `desci`，
/// 再加 2026-09-18 美股新拆出来的「软件」「电力」）。
///
/// 这一份是原型 `sector-icons.js`（2026-09-18 冻结）的移植——路径、身份色、内缩比例、
/// 描边宽度一个数都没动。那些形是在原型上逐枚看过定下来的，这里只负责把它们画到
/// SwiftUI 上，画法照品种徽章（`CoinBadge.swift`）：
///
/// · **底板是一块渐变的圆**，不是徽章那种圆角方块。徽章站在列表行里，方块和行是一路的；
///   板块记号是一枚圆章，和行里的品种徽章一眼分得开（原型定稿时它压在气泡的球面上，
///   2026-09-24 气泡撤了，圆留着）。
/// · **上色跟着皮肤走**，走的就是徽章那套 `BadgeTint`：色相往皮肤强调色偏一小步、
///   饱和度封顶、明度收进窄带、深色再压暗一档。所以每枚只声明自己的 `from` / `to`
///   身份色，三套皮肤 × 深浅共八种组合由那段变换负责，这儿不写第二处颜色。
/// · **描边宽度走 `BadgeLine`**：收进 1.86…2.16 的窄带，再按尺寸开 0.72 次方。
///   一屏三十几枚记号并排，笔锋得是一致的。
/// · 记号一律**实心圆润有色彩材质**——以实心填充为主，只有天平、棱镜的分光、矿镐的柄
///   那几笔是描边，而且圆头圆角。单色细线线框那种画法在这个项目里被否过两次。
///
/// 三种笔画和原型的 `strokes` 一一对应：`stroke == nil && !eo` 是 nonzero 实心，
/// `stroke == nil && eo` 是 even-odd 实心（在记号上挖洞，41 枚里有 22 枚用到），
/// `stroke` 给了数值就是描边，数值是 24 格坐标系里声明的宽度。
public struct SectorIconArt: Sendable, Equatable {
  public let id: String
  public let name: String
  public let market: SectorMarket
  /// 所属族（`SectorIcons.families` 的键）。族决定这一枚走哪支色相。
  public let fam: String
  /// 色相键（`SectorIcons.palette` 的键）。
  public let hue: String
  /// 色相的哪一档：`"L"` 浅 / `"M"` 中 / `"D"` 深。同族的几枚靠这一档分开。
  public let tone: String
  /// 渐变左上那头的原色。这是记号自己的身份色，是全项目里唯一允许写字面 hex 的地方。
  public let from: String
  /// 渐变右下那头的原色。
  public let to: String
  /// 记号占底板直径的比例（`CoinSpec.inset` 同义）。
  public let inset: CGFloat

  /// 一层笔画。一枚记号最多两层——比如火箭是「挖了舷窗的弹体」加「尾翼和火焰」，
  /// 一层 even-odd 一层实心。
  public struct Part: Sendable, Equatable {
    /// 24×24 `viewBox` 的路径，只有 M / L / C / A / Z 五个绝对命令。
    public let d: [String]
    /// 描边宽度（24 格坐标系里声明的）。`nil` = 实心填充。
    public let stroke: Double?
    /// 实心填充用 even-odd。挖洞的那 22 枚靠它，nonzero 会把洞填死。
    public let eo: Bool
  }

  public let parts: [Part]
}

// MARK: - 色相与族

/// 一支色相的三档。板块记号只用这六支色相，靠 L / M / D 三档把同族的几枚分开——
/// 同族用同一支色是为了「一眼看出是一类」，分档是为了「再看一眼分得出是哪一枚」。
struct SectorHue: Sendable, Equatable {
  struct Pair: Sendable, Equatable {
    let from: String
    let to: String
    init(_ from: String, _ to: String) {
      self.from = from
      self.to = to
    }
  }

  let key: String
  /// 中文名，只在盘点和说明里用，不上界面。
  let name: String
  /// 这支色相占的角度区间，同样只是记账。
  let range: String
  let light: Pair
  let mid: Pair
  let deep: Pair

  func tone(_ t: String) -> Pair {
    switch t {
    case "L": light
    case "D": deep
    default: mid
    }
  }
}

/// 一个族。族是「这一屏上哪几枚该长得像一家」的划分，`why` 是定稿时的理由，
/// 留着是因为以后加板块要照这条线分色，不能随手挑一支没人用过的颜色。
struct SectorFamily: Sendable, Equatable {
  let key: String
  let market: SectorMarket
  let name: String
  /// 这一族走哪支色相（`SectorIcons.palette` 的键）。
  let hue: String
  let why: String
}

// MARK: - 上色、笔画、内缩

/// 记号的三样度量，全是原型里那三个函数的移植。
enum SectorInk {
  /// 一对渐变端点。
  ///
  /// 原型的 `sectorTint()` 本来就是 `BadgeTint` 的一比一 JS 移植，所以这儿不再抄一遍，
  /// 直接把身份色喂回 `BadgeTint`——两处颜色永远是同一套算法，皮肤一改两处一起改。
  ///
  /// 原型里那张 `SECTOR_SKIN_ACCENT` 表（青苔 `#2E7D6B` / `#4FB69C`、陶土 `#B25735` /
  /// `#E2874F`…）在 Swift 这边就是 `PaletteSeed.accent` 本身，一个值都不用再写：
  /// 前两套逐字对得上。只有「经典」对不上——原型给它配了一支蓝，而 app 里经典那套种子
  /// 的强调色沿用青苔的墨绿。这儿以种子为准，理由有二：面板里不许写字面 hex；
  /// 而且真按原型那支蓝走，经典皮肤下整屏只有板块记号往一支别处不存在的蓝偏，
  /// 反倒是它自己跳出来。
  static func gradient(_ art: SectorIconArt, theme: PanelTheme) -> (top: Color, bottom: Color) {
    BadgeTint.gradient(from: Hex(art.from), to: Hex(art.to), seed: theme.seed)
  }

  /// 描边宽度：和徽章共用一条窄带（`BadgeLine`），`size` 是底板直径。
  static func weight(_ declared: Double, at size: CGFloat) -> Double {
    BadgeLine.weight(declared, at: size)
  }

  /// 记号占底板的比例，带一道光学修正。
  ///
  /// 和 `BadgeLine` 是一个道理：直径小于 20 时按比例缩会显得空，所以把记号放大最多一成，
  /// 把仅有的那几个像素全用在剪影上，上限 0.82（再往外就贴到底板的边了）。
  static func inset(_ base: CGFloat, at size: CGFloat) -> CGFloat {
    let k = min(max((20 - size) / 8, 0), 1)
    return min(base * (1 + 0.10 * k), 0.82)
  }
}

// MARK: - 视图

/// 记号视图：底板 + 记号。`size` 是外框边长（也就是底板直径）。
///
/// 用在板块列表的每一行和品种列表的头部。
struct SectorIconView: View {
  var art: SectorIconArt
  var size: CGFloat

  /// 上色要跟着当前皮肤走，所以得知道现在是哪一套。
  @Environment(\.panelTheme) private var theme

  var body: some View {
    let ink = SectorInk.gradient(art, theme: theme)
    return Circle()
      .fill(LinearGradient(colors: [ink.top, ink.bottom],
                           startPoint: .topLeading, endPoint: .bottomTrailing))
      .frame(width: size, height: size)
      .overlay { SectorMark(art: art, size: size) }
      // 影子只是让它离纸面一点点，尺度照徽章那一枚（0.2 以内，在青苔那种极浅的底上
      // 才不会洇成一团彩色墨点）。
      .shadow(color: ink.bottom.opacity(theme.dark ? 0.26 : 0.18),
              radius: size * 0.17, x: 0, y: size * 0.1)
      .accessibilityHidden(true)
  }
}

/// 只画记号本身，不要底板。`size` 仍是底板直径——内缩和描边宽度都是按直径算的，
/// 传记号自己的边长会让这一枚和别处的粗细对不上。
struct SectorMark: View {
  var art: SectorIconArt
  var size: CGFloat
  /// 记号的颜色。默认白：它总是压在自己那块底板上。
  var ink: Color = .white

  var body: some View {
    let box = size * SectorInk.inset(art.inset, at: size)
    return ZStack {
      ForEach(Array(art.parts.enumerated()), id: \.offset) { _, part in
        if let width = part.stroke {
          SectorShape(paths: part.d)
            .stroke(ink, style: StrokeStyle(lineWidth: SectorInk.weight(width, at: size),
                                            lineCap: .round, lineJoin: .round))
        } else {
          SectorShape(paths: part.d).fill(ink, style: FillStyle(eoFill: part.eo))
        }
      }
    }
    .frame(width: box, height: box)
    .accessibilityHidden(true)
  }
}

/// 24×24 的 `viewBox` 原样拿来，等比缩到目标边长。解析走 `SVGPath.parsed` 的缓存，
/// 这儿只剩一次等比变换——和 `CoinBadge` 里那个 `CoinShape` 是同一件事。
private struct SectorShape: Shape {
  var paths: [String]

  func path(in rect: CGRect) -> Path {
    SVGPath.parsed(paths).applying(CGAffineTransform(scaleX: rect.width / 24, y: rect.height / 24))
  }
}

